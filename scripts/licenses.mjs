// ---- SPDX expressions -------------------------------------------------------

/** "A OR (B AND C)" → alternatives, each a list of licence ids. Old "A/B" means OR. */
function alternatives(expr) {
  const tokens = expr
    .replace(/\s*\/\s*/g, " OR ")
    .replace(/([()])/g, " $1 ")
    .split(/\s+/)
    .filter(Boolean);
  let i = 0;
  const atom = () => {
    if (tokens[i] === "(") {
      i++;
      const e = or();
      i++; // ")"
      return e;
    }
    let id = tokens[i++];
    if (tokens[i] === "WITH") {
      id += ` WITH ${tokens[i + 1]}`;
      i += 2;
    }
    return [[id]];
  };
  const and = () => {
    let left = atom();
    while (tokens[i] === "AND") {
      i++;
      const right = atom();
      left = left.flatMap((a) => right.map((b) => [...a, ...b]));
    }
    return left;
  };
  const or = () => {
    let alts = and();
    while (tokens[i] === "OR") {
      i++;
      alts = alts.concat(and());
    }
    return alts;
  };
  return or();
}

// ---- Licence texts ----------------------------------------------------------

/** The licences a text is (a file may hold several). */
function kinds(raw) {
  // Licences kept as source comments ("// Permission to use…") read the same.
  const t = raw.replace(/^[ \t]*(\/\/+|#+|\*+|\/\*+|;+)[ \t]?/gm, "").replace(/\s+/g, " ");
  const out = new Set();
  const ofl = /SIL OPEN FONT LICENSE,? (?:Version |v)1\.1/i.test(t);
  // OFL grants permission in similar words but is not a second MIT licence.
  const mitLike = !ofl && /Permission is hereby granted, free of charge, to any person/i.test(t);
  if (mitLike) out.add(/shall be included in all copies/i.test(t) ? "MIT" : "MIT-0");
  if (/Apache License,? Version 2\.0/i.test(t) && /TERMS AND CONDITIONS FOR USE/i.test(t)) out.add("Apache-2.0");
  if (/LLVM Exceptions/i.test(t)) out.add("Apache-2.0 WITH LLVM-exception");
  if (/Redistribution and use in source and binary forms/i.test(t)) {
    if (/Neither the name/i.test(t) || /names of (its|the) contributors may/i.test(t)) out.add("BSD-3-Clause");
    else if (/Redistributions in binary form/i.test(t)) out.add("BSD-2-Clause");
    else out.add("BSD-1-Clause");
  }
  if (/Permission to use, copy, modify,? and\/or distribute this software for any purpose with or without fee is hereby granted/i.test(t)) {
    out.add(/provided that the above copyright notice/i.test(t) ? "ISC" : "0BSD");
  }
  if (/provided 'as-is', without any express or implied warranty/i.test(t) && /plainly marked/i.test(t)) out.add("Zlib");
  if (/free and unencumbered software released into the public domain/i.test(t)) out.add("Unlicense");
  if (/CC0 1\.0 Universal/i.test(t)) out.add("CC0-1.0");
  if (/Boost Software License - Version 1\.0/i.test(t)) out.add("BSL-1.0");
  if (/Mozilla Public License,? Version 2\.0/i.test(t)) out.add("MPL-2.0");
  if (/UNICODE LICENSE V3/i.test(t)) out.add("Unicode-3.0");
  if (/UNICODE, INC\. LICENSE AGREEMENT/i.test(t)) out.add("Unicode-DFS-2016");
  if (/Community Data License Agreement\s*-\s*Permissive\s*-\s*Version 2\.0/i.test(t)) out.add("CDLA-Permissive-2.0");
  if (/GNU LESSER GENERAL PUBLIC LICENSE/i.test(t)) out.add("LGPL-2.1-or-later");
  if (ofl) out.add("OFL-1.1");
  return out;
}

/** A file name's hint at its licence ("LICENSE-MIT"), to prefer it over a general one. */
function nameHint(file, id) {
  const n = file.toLowerCase();
  const key = { MIT: "mit", "Apache-2.0": "apache", "BSD-3-Clause": "bsd", "BSD-2-Clause": "bsd", Zlib: "zlib", ISC: "isc", Unlicense: "unlicense", "BSL-1.0": "boost" }[id];
  return key && n.includes(key) ? 0 : 1;
}

const normalize = (s) =>
  s
    .replace(/^﻿/, "")
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .map((l) => l.replace(/\s+$/, ""))
    .join("\n")
    .trim();

const LICENCE_FILE = /^(licen[cs]e|copying|unlicense|copyright|notice|ofl)/i;

/** Licence-like files in a package folder (and a LICENSES/ folder in it). */
function licenceFiles(dir) {
  const out = [];
  let names = [];
  try {
    names = readdirSync(dir);
  } catch {
    return out;
  }
  for (const n of names.sort()) {
    const p = join(dir, n);
    let st;
    try {
      st = statSync(p);
    } catch {
      continue;
    }
    if (st.isDirectory() && /^\.?licen[cs]es?$/i.test(n)) {
      for (const m of readdirSync(p).sort()) {
        const q = join(p, m);
        if (statSync(q).isFile()) out.push({ file: `${n}/${m}`, text: normalize(readFileSync(q, "utf8")) });
      }
    } else if (st.isFile() && LICENCE_FILE.test(n) && st.size < 200_000) {
      out.push({ file: n, text: normalize(readFileSync(p, "utf8")) });
    }
  }
  return out;
}

/**
 * Pick the licence to use a package under and the texts that go with it:
 * the alternative with texts for all of its licences, preferring PREFERENCE.
 * Copyright and NOTICE files always come along.
 */
function resolve(pkg) {
  const files = pkg.files.map((f) => ({ ...f, kinds: kinds(f.text) }));
  const alts = alternatives(pkg.expr);
  const has = (id) => files.some((f) => f.kinds.has(id));
  const score = (alt) => alt.reduce((s, id) => s + rank(id) + (has(id) ? 0 : 1000), 0);
  const chosen = [...alts].sort((a, b) => score(a) - score(b))[0];
  const texts = [];
  const missing = [];
  for (const id of chosen) {
    const match = files
      .filter((f) => f.kinds.has(id))
      .sort((a, b) => nameHint(a.file, id) - nameHint(b.file, id) || a.file.length - b.file.length)[0];
    if (match) {
      if (!texts.includes(match)) texts.push(match);
      // Several copyright holders, one text each (a licences folder): all of them.
      for (const f of files) if (f.kinds.has(id) && f.file.includes("/") && !texts.some((t) => t.text === f.text)) texts.push(f);
    } else missing.push(id);
  }
  for (const f of files) {
    const base = f.file.split("/").pop();
    // Copyright and NOTICE files, and notes on how the licences apply.
    const note = /^licen[cs]e/i.test(base) && !f.kinds.size;
    if ((note || /^(copyright|notice)/i.test(base)) && !texts.includes(f)) texts.push(f);
  }
  return { ...pkg, chosen, texts, missing };
}

// ---- Packages ---------------------------------------------------------------

function cargoMetadata() {
  const args = ["metadata", "--format-version", "1", "--locked"];
  const opts = { cwd: ROOT, maxBuffer: 256 * 1024 * 1024, stdio: ["ignore", "pipe", "inherit"] };
  try {
    return JSON.parse(execFileSync("cargo", [...args, "--offline"], { ...opts, stdio: ["ignore", "pipe", "ignore"] }));
  } catch {
    return JSON.parse(execFileSync("cargo", args, opts));
  }
}

function rustPackages() {
  const meta = cargoMetadata();
  const own = new Set(meta.workspace_members);
  return meta.packages
    .filter((p) => !own.has(p.id))
    .map((p) => {
      const dir = dirname(p.manifest_path);
      const files = licenceFiles(dir);
      if (p.license_file) {
        const f = join(dir, p.license_file);
        if (existsSync(f) && !files.some((x) => join(dir, x.file) === f)) files.push({ file: p.license_file, text: normalize(readFileSync(f, "utf8")) });
      }
      return {
        eco: p.source ? "Rust" : "Rust (vendored)",
        name: p.name,
        version: p.version,
        expr: p.license || "NOASSERTION",
        authors: (p.authors || []).map((a) => a.replace(/\s*<[^>]*>/, "")),
        repository: p.repository || "",
        files,
      };
    });
}

function npmPackages() {
  const lock = JSON.parse(readFileSync(join(UI, "package-lock.json"), "utf8"));
  if (!existsSync(join(UI, "node_modules"))) throw new Error("apps/tessera/ui/node_modules is missing: run `npm ci` there first");
  return Object.entries(lock.packages)
    .filter(([key, v]) => key && !v.dev)
    .map(([key, v]) => {
      const dir = join(UI, key);
      if (!existsSync(dir)) throw new Error(`${key} is not installed: run \`npm ci\` in apps/tessera/ui`);
      const pj = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
      const author = typeof pj.author === "string" ? pj.author : pj.author?.name;
      return {
        eco: "JavaScript",
        name: key.replace(/^.*node_modules\//, ""),
        version: v.version,
        expr: (v.license || pj.license || "NOASSERTION").replace(/^\((.*)\)$/, "$1"),
        authors: author ? [author.replace(/\s*<[^>]*>/, "")] : [],
        repository: typeof pj.repository === "string" ? pj.repository : pj.repository?.url || "",
        files: licenceFiles(dir),
      };
    });
}

function extraPackages() {
  return EXTRAS.map((e) => ({
    ...e,
    authors: [],
    repository: "",
    files: e.files.map((f) => ({ file: f.split("/").pop(), text: normalize(readFileSync(join(ROOT, f), "utf8")) })),
  }));
}

// ---- Output -----------------------------------------------------------------

const label = (p) => (p.version ? `${p.name} ${p.version}` : p.name);
const RULE = "-".repeat(78);
const ECO_ORDER = ["Rust", "Rust (vendored)", "JavaScript", "Bundled"];

function wrap(text, width = 78, indent = "") {
  const words = text.split(" ");
  const lines = [];
  let line = indent;
  for (const w of words) {
    if (line.trim() && (line + " " + w).length > width) {
      lines.push(line);
      line = indent + w;
    } else line = line.trim() ? `${line} ${w}` : indent + w;
  }
  if (line.trim()) lines.push(line);
  return lines.join("\n");
}

function render(pkgs) {
  // One section per distinct text, listing every package that ships it.
  const groups = new Map();
  for (const p of pkgs) {
    for (const t of p.texts) {
      const g = groups.get(t.text) ?? { text: t.text, kinds: kinds(t.text), users: [] };
      g.users.push(p);
      groups.set(t.text, g);
    }
  }
  const sorted = [...groups.values()].sort((a, b) => {
    const ka = [...a.kinds].sort().join() || "~";
    const kb = [...b.kinds].sort().join() || "~";
    return ka.localeCompare(kb) || label(a.users[0]).localeCompare(label(b.users[0])) || a.text.localeCompare(b.text);
  });
  const missing = pkgs.filter((p) => p.missing.length);
  const standard = new Set(missing.flatMap((p) => p.missing));

  const out = [];
  out.push("THIRD-PARTY LICENCES");
  out.push("====================");
  out.push("");
  out.push(
    wrap(
      "Tessera is licensed under the Apache License 2.0 (see LICENSE). It is built from the third-party software below, each under its own licence. This file holds their licence texts and copyright notices, as those licences ask. Where a package offers a choice of licences, Tessera uses it under the one named after \"used under\". THIRD_PARTY_NOTICES.md explains what is where, and lists software that Tessera downloads from its makers instead of bundling it.",
    ),
  );
  out.push("");
  out.push(wrap("Generated by scripts/licenses.mjs from Cargo.lock, apps/tessera/ui/package-lock.json and the bundled files it names. Don't edit it by hand: run `node scripts/licenses.mjs`."));
  out.push("");
  const counts = ECO_ORDER.map((e) => [e, pkgs.filter((p) => p.eco === e).length]).filter(([, n]) => n);
  out.push(`Packages: ${counts.map(([e, n]) => `${n} ${e}`).join(", ")}.`);
  out.push(`Part 1: ${sorted.length} licence texts and notices, with the packages that ship each one.`);
  out.push(`Part 2: ${missing.length} packages that ship no licence file of their own.`);
  out.push(`Part 3: the standard texts of ${[...standard].sort().join(", ") || "no licences"}, for part 2.`);
  out.push("");
  out.push("");
  out.push("PART 1. LICENCE TEXTS AND NOTICES");
  out.push("");
  sorted.forEach((g, i) => {
    out.push(RULE);
    const kindsTxt = [...g.kinds].sort().join(", ") || "notice";
    out.push(`[${i + 1}] ${kindsTxt}`);
    for (const eco of ECO_ORDER) {
      const users = g.users.filter((p) => p.eco === eco);
      if (!users.length) continue;
      const names = users.map((p) => `${label(p)} (used under ${p.chosen.join(" AND ")})`).sort();
      out.push(wrap(`${eco}: ${names.join(", ")}`, 78, "    ").replace(/^ {4}/, "    "));
    }
    out.push(RULE);
    out.push("");
    out.push(g.text);
    out.push("");
    out.push("");
  });
  out.push("PART 2. PACKAGES WITHOUT A LICENCE FILE");
  out.push("");
  out.push(
    wrap(
      "These packages declare their licence in their package metadata but ship no licence file. The copyright holders are the package's authors as listed there. The licence texts are in part 3.",
    ),
  );
  out.push("");
  for (const p of [...missing].sort((a, b) => label(a).localeCompare(label(b)))) {
    const who = p.authors.length ? p.authors.join(", ") : `the ${p.name} authors`;
    out.push(`- ${label(p)} (${p.eco}): ${p.missing.join(" AND ")}. Copyright (c) ${who}.${p.repository ? ` Source: ${p.repository}` : ""}`);
  }
  out.push("");
  out.push("");
  out.push("PART 3. STANDARD LICENCE TEXTS");
  out.push("");
  for (const id of [...standard].sort()) {
    out.push(RULE);
    out.push(id);
    out.push(RULE);
    out.push("");
    if (id === "MIT") {
      out.push("MIT License\n\nCopyright (c) <the package's authors, listed in part 2>\n\n" + MIT_BODY);
    } else if (id === "Apache-2.0") {
      out.push(normalize(readFileSync(join(ROOT, "LICENSE"), "utf8")));
    } else {
      // The first full text of this licence any package ships.
      const any = pkgs.flatMap((p) => p.files).find((f) => kinds(f.text).has(id) && f.text.length > 1500);
      out.push(any ? any.text : `See https://spdx.org/licenses/${id}.html`);
    }
    out.push("");
    out.push("");
  }
  return out.join("\n").replace(/\n+$/, "\n");
}

function summary(pkgs) {
  const out = [BEGIN, ""];
  for (const eco of ECO_ORDER) {
    const list = pkgs.filter((p) => p.eco === eco);
    if (!list.length) continue;
    const title = { Rust: "Rust crates", "Rust (vendored)": "Rust crates kept in this repository", JavaScript: "JavaScript packages in the apps' interface", Bundled: "Libraries and fonts kept in this repository" }[eco];
    out.push(`**${title}** (${list.length}):`);
    out.push("");
    const rows = new Map();
    for (const p of list) {
      const key = `${p.expr}\u0000${p.chosen.join(" AND ")}`;
      const r = rows.get(key) ?? { expr: p.expr, chosen: p.chosen.join(" AND "), names: new Set() };
      r.names.add(p.name);
      rows.set(key, r);
    }
    for (const r of [...rows.values()].sort((a, b) => b.names.size - a.names.size || a.expr.localeCompare(b.expr))) {
      const names = [...r.names].sort();
      // A list rather than a table: the names wrap well on a phone too.
      const used = r.chosen === r.expr ? "" : ` (used under ${r.chosen})`;
      out.push(`- **${r.expr}**${used}${names.length > 1 ? `, ${names.length}` : ""}: ${names.join(", ")}`);
    }
    out.push("");
  }
  out.push(END);
  return out.join("\n");
}

// ---- Main -------------------------------------------------------------------

const pkgs = [...rustPackages(), ...npmPackages(), ...extraPackages()].map(resolve);
pkgs.sort((a, b) => ECO_ORDER.indexOf(a.eco) - ECO_ORDER.indexOf(b.eco) || a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const txt = render(pkgs);
const md0 = readFileSync(OUT_MD, "utf8");
const a = md0.indexOf(BEGIN);
const b = md0.indexOf(END);
if (a < 0 || b < a) throw new Error(`THIRD_PARTY_NOTICES.md lacks the ${BEGIN} … ${END} markers`);
const md = md0.slice(0, a) + summary(pkgs) + md0.slice(b + END.length);

const unknown = pkgs.filter((p) => p.expr === "NOASSERTION");
if (unknown.length) console.error(`No declared licence: ${unknown.map(label).join(", ")}`);

if (check) {
  const old = existsSync(OUT_TXT) ? readFileSync(OUT_TXT, "utf8") : "";
  const stale = [old !== txt && relative(ROOT, OUT_TXT), md0 !== md && relative(ROOT, OUT_MD)].filter(Boolean);
  if (stale.length) {
    console.error(`Out of date: ${stale.join(", ")}. Run \`node scripts/licenses.mjs\`.`);
    process.exit(1);
  }
  console.log(`Third-party licences are up to date (${pkgs.length} packages).`);
} else {
  writeFileSync(OUT_TXT, txt);
  writeFileSync(OUT_MD, md);
  const miss = pkgs.filter((p) => p.missing.length).length;
  console.log(`${pkgs.length} packages, ${(txt.length / 1024).toFixed(0)} KB of licence texts; ${miss} without a licence file of their own.`);
}

#!/usr/bin/env node
// Third-party licences. Writes THIRD_PARTY_LICENSES.txt (the licence texts
// and copyright notices of every Rust crate and JavaScript package Tessera is
// built from, plus the bundled whiteboard libraries and fonts) and the
// generated part of THIRD_PARTY_NOTICES.md (a summary by licence).
//
//   node scripts/licenses.mjs           write both
//   node scripts/licenses.mjs --check   exit 1 if either is out of date
//
// Needs `cargo` (crate sources come from Cargo's cache; it downloads missing
// ones) and the interface's packages (`npm ci` in apps/tessera/ui). Run it
// after changing Cargo.lock or package-lock.json. No dependencies of its own.


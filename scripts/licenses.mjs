const OUT_TXT = join(ROOT, "THIRD_PARTY_LICENSES.txt");
const OUT_MD = join(ROOT, "THIRD_PARTY_NOTICES.md");
const BEGIN = "<!-- BEGIN GENERATED by scripts/licenses.mjs: don't edit by hand -->";
const END = "<!-- END GENERATED -->";
const check = process.argv.includes("--check");


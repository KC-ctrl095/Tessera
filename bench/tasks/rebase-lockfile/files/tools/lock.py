#!/usr/bin/env python3
"""Generate deps.lock from requirements.in and the package index snapshot.

    python3 tools/lock.py           # write deps.lock
    python3 tools/lock.py --check   # exit 1 when deps.lock is out of date (CI runs this on every commit)

Every package gets the newest version in tools/index.json that satisfies all
constraints on it (from requirements.in and from the dependencies of the
chosen versions of other packages), repeated until nothing changes. The lock
file lists the pins sorted by name, each with what pulled it in, under a
header holding a hash of the inputs. Never edit deps.lock by hand: change
requirements.in (or refresh tools/index.json) and run this again.
"""

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "requirements.in"
INDEX = ROOT / "tools" / "index.json"
LOCK = ROOT / "deps.lock"

SPEC = re.compile(r"^\s*(>=|<=|==|!=|~=|>|<)\s*([0-9][0-9.]*)\s*$")
REQ = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)\s*(.*)$")


class LockError(Exception):
    pass


def version(text):
    return tuple(int(p) for p in text.split("."))


def canonical(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_requirement(line):
    m = REQ.match(line.strip())
    if not m:
        raise LockError(f"can't read requirement {line!r}")
    name, rest = canonical(m.group(1)), m.group(2).strip()
    specs = []
    for part in filter(None, (p.strip() for p in rest.split(","))):
        sm = SPEC.match(part)
        if not sm:
            raise LockError(f"can't read version constraint {part!r} in {line!r}")
        specs.append((sm.group(1), version(sm.group(2))))
    return name, specs


def satisfies(v, op, want):
    if op == ">=":
        return v >= want
    if op == "<=":
        return v <= want
    if op == ">":
        return v > want
    if op == "<":
        return v < want
    if op == "==":
        return v == want
    if op == "!=":
        return v != want
    if op == "~=":  # compatible release: ~=1.4.2 means >=1.4.2, ==1.4.*
        return v >= want and v[: len(want) - 1] == want[: len(want) - 1]
    raise LockError(op)


def read_requirements(text):
    reqs = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            reqs.append(parse_requirement(line))
    return reqs


def resolve(reqs, index):
    packages = {canonical(k): v for k, v in index["packages"].items()}
    top = {name for name, _ in reqs}
    pins = {}
    for _ in range(50):
        constraints = {}  # name -> [(op, version, source)]
        for name, specs in reqs:
            constraints.setdefault(name, []).extend((op, v, "requirements.in") for op, v in specs)
        for name, ver in sorted(pins.items()):
            for dep in packages[name][ver]:
                dname, dspecs = parse_requirement(dep)
                constraints.setdefault(dname, []).extend((op, v, name) for op, v in dspecs)
                constraints[dname].append(("", None, name))  # records who needs it, even without a constraint
        new = {}
        for name, cons in sorted(constraints.items()):
            if name not in packages:
                raise LockError(f"{name} is not in the package index")
            ok = [s for s in packages[name] if all(op == "" or satisfies(version(s), op, v) for op, v, _ in cons)]
            if not ok:
                raise LockError(f"no version of {name} satisfies " + ", ".join(f"{op}{'.'.join(map(str, v))} ({src})" for op, v, src in cons if op))
            new[name] = max(ok, key=version)
        if new == pins:
            break
        pins = new
    else:
        raise LockError("resolution doesn't settle")
    via = {name: set() for name in pins}
    for name in top:
        via[name].add("requirements.in")
    for name, ver in pins.items():
        for dep in packages[name][ver]:
            via[parse_requirement(dep)[0]].add(name)
    return pins, via


def render(req_text, index_text):
    index = json.loads(index_text)
    pins, via = resolve(read_requirements(req_text), index)
    normalized = "\n".join(sorted(line.split("#", 1)[0].strip() for line in req_text.splitlines() if line.split("#", 1)[0].strip()))
    digest = hashlib.sha256((normalized + "\n--\n" + json.dumps(index, sort_keys=True)).encode()).hexdigest()[:16]
    out = [
        "# deps.lock: generated by tools/lock.py from requirements.in and tools/index.json.",
        "# Do not edit by hand; run `python3 tools/lock.py` instead.",
        f"# inputs: sha256:{digest}",
    ]
    for name in sorted(pins):
        out.append(f"{name + '==' + pins[name]:<32}# via {', '.join(sorted(via[name], key=lambda s: (s != 'requirements.in', s)))}")
    return "\n".join(out) + "\n"


def main(argv):
    try:
        text = render(REQUIREMENTS.read_text(encoding="utf-8"), INDEX.read_text(encoding="utf-8"))
    except LockError as e:
        print(f"lock.py: {e}", file=sys.stderr)
        return 2
    if "--check" in argv:
        current = LOCK.read_text(encoding="utf-8") if LOCK.exists() else ""
        if current != text:
            print("deps.lock is out of date: run `python3 tools/lock.py`", file=sys.stderr)
            return 1
        print("deps.lock is up to date")
        return 0
    LOCK.write_text(text, encoding="utf-8")
    print(f"wrote {LOCK.name}: {len(text.splitlines()) - 3} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
